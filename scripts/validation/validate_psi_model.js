'use strict';
const PSI=require('../../js/psi-model.js');
const assert=(cond,msg)=>{if(!cond)throw new Error(msg)};
const approx=(a,b,t)=>Math.abs(a-b)<=t;
const serial=x=>PSI.serializable(PSI.compute(x));
const base=serial({}),cant0=serial({cant:0,spread:14}),cant14=serial({cant:14,spread:14}),spread8=serial({cant:6,spread:8}),spread22=serial({cant:6,spread:22}),low=serial({altitude:8}),high=serial({altitude:32}),tl=serial({throttle:25}),th=serial({throttle:100}),resistant=serial({regolith:'resistant'}),erodible=serial({regolith:'erodible'}),hwNear=serial({hardwareDistance:8,cant:12,spread:20,altitude:12}),hwFar=serial({hardwareDistance:80,cant:12,spread:20,altitude:12});
assert(base.area>0,'Baseline area invalid');
assert(Math.abs(cant0.centroidX)<.08&&cant14.centroidX>cant0.centroidX+3,'Cant must shift footprint direction');
assert(spread22.area>spread8.area*5&&spread22.crossWidth>spread8.crossWidth*2,'Spread must widen footprint');
assert(high.area>low.area*10&&low.loadingRatio>high.loadingRatio*10,'Altitude sensitivity incorrect');
assert(approx(tl.area,th.area,.01)&&th.loadingRatio>tl.loadingRatio*3.9,'Throttle must change loading proxy, not geometry');
assert(approx(resistant.area,erodible.area,.01)&&erodible.erosionRatio>resistant.erosionRatio*2,'Surface response sensitivity incorrect');
assert(hwNear.hardwareLevel!==hwFar.hardwareLevel&&hwFar.clearance>hwNear.clearance,'Hardware screening incorrect');
for(const obj of [base,cant0,cant14,spread8,spread22,low,high,tl,th,resistant,erodible,hwNear,hwFar])for(const v of Object.values(obj))if(typeof v==='number')assert(Number.isFinite(v),'Non-finite model output');
console.log('A2 MissionLab PSI pure-model regression');
console.log('PASS: cant changes direction/offset');
console.log('PASS: spread changes divergence/area');
console.log('PASS: altitude changes geometry and normalized loading');
console.log('PASS: thrust changes proxy without changing geometry');
console.log('PASS: surface class changes erosion sensitivity only');
console.log('PASS: hardware distance changes screening state');
console.log('PASS: all numeric outputs finite');
console.log(JSON.stringify({base,cant14,spread8,spread22,low,high,hwNear,hwFar},null,2));
